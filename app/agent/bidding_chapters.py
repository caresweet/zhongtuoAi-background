def get_bidding_chapters(report_type: str) -> List[Dict[str, Any]]:
    """Return the chapter outline list for a bidding report type."""
    return BIDDING_CHAPTER_STRUCTURES.get(
        report_type, BIDDING_CHAPTER_STRUCTURES["summary"]
    )


