def _schedule(rows_src, start: int) -> Rows:
    """把 (天数跨度, 工作内容, 主要任务, 负责, 交付成果) 拼成「第a–b日」行。"""
    rows: Rows = []
    day = start
    for span, work, task, who, out in rows_src:
        rows.append([f"第 {day}–{day + span - 1} 日", work, task, who, out])
        day += span
    return rows


