def t_gantt(ctx) -> Spec:
    d = _dur(ctx)
    n = 9
    step = max(math.ceil(d / n), 1)
    headers = ["工作内容\\日"] + [f"{i * step + 1}-{min((i + 1) * step, d)}"
                                 for i in range(n)]
    tasks = [
        ("项目启动与资料收集", 0, 1),
        ("权属调查与指界", 1, 2),
        ("地类认定与勘测定界", 2, 3),
        ("面积汇总与图件编制", 3, 5),
        ("报批文本编制", 4, 6),
        ("内部三级校审", 5, 6),
        ("电子报件与组卷", 6, 7),
        ("逐级申报与跟踪", 7, 8),
        ("补正响应", 7, 9),
        ("批复取得与移交", 8, 9),
    ]
    rows: Rows = []
    for name, a, b in tasks:
        cells = ["●" if a <= i < b else "" for i in range(n)]
        rows.append([name] + cells)
    return {"caption": "表4-6 项目全周期甘特图式进度总表",
            "headers": headers, "rows": rows}


