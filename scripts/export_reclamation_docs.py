from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

BACKEND = Path(__file__).resolve().parent.parent
OUT = BACKEND.parent / "docs"

_HEAD_FILL = PatternFill("solid", fgColor="1F4E79")
_HEAD_FONT = Font(color="FFFFFF", bold=True, size=11)
_Y_ = PatternFill("solid", fgColor="E2EFDA")   # 有 / 是
_N_ = PatternFill("solid", fgColor="FCE4E4")   # 缺 / 否
_W_ = PatternFill("solid", fgColor="FFF2CC")   # 部分 / 可生成
_THIN = Side(style="thin", color="BFBFBF")
_BORDER = Border(left=_THIN, right=_THIN, top=_THIN, bottom=_THIN)


def _sheet(wb, title, headers, rows, widths, marks_col=None):
    ws = wb.create_sheet(title)
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(1, c)
        cell.fill = _HEAD_FILL
        cell.font = _HEAD_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for r in rows:
        ws.append(list(r))
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = _BORDER
        if marks_col:
            v = str(row[marks_col - 1].value or "")
            if v.startswith(("✅", "是")):
                row[marks_col - 1].fill = _Y_
            elif v.startswith(("❌", "否", "无")):
                row[marks_col - 1].fill = _N_
            elif v.startswith(("⚠", "部分", "可")):
                row[marks_col - 1].fill = _W_
    ws.freeze_panes = "A2"
    return ws


