# 第一章：地块差异分析
# ═══════════════════════════════════════════════════════════════
def t_plots(ctx) -> Spec:
    plots = ctx.get("plots") or []
    rows: Rows = []
    if plots:
        total = max(_dur(ctx) - 30, 30)
        n = max(len(plots), 1)
        for i, pl in enumerate(plots, 1):
            name = str(pl.get("name") or "地块")
            try:
                area = float(pl.get("area") or 0)
            except Exception:
                area = 0.0
            # 重点难点按地块特征区分（人工稿四行内容各不相同）
            if "产业园" in name or "先导区" in name:
                diff = "分期开发，先导区与园区总规衔接、报批范围界定要求高"
                special = "先导区分期报批，须与园区规划及后续批次衔接"
            elif area >= 200:
                diff = "地块规模大、涉及村组多，指界与地类认定协调量大"
                special = "耕地占补平衡指标、社保审核要件须提前落实"
            elif 0 < area < 50:
                diff = "地块规模小但权属与企业用地边界交错，现状核查要求细"
                special = "企业投资项目，须与建设单位确认红线与建设时序"
            else:
                diff = "村域权属交错、地类认定与指界协调量大"
                special = "耕地占补平衡指标、社保审核要件须提前落实"
            loc = str(pl.get("location") or "").strip()
            if loc and loc not in diff:
                diff = f"{diff}（涉及{loc}）"
            rows.append([
                f"{i}、{name}",
                pl.get("type") or "批次用地报批",
                (f"{pl.get('area')} 亩" if pl.get("area") else "以勘测定界为准"),
                diff, special,
                f"约 {max(int(total / n), 10)} 天",
            ])
    else:
        parts = [x.strip() for x in str(ctx.get("project") or "本项目")
                 .replace("项目", "").replace("报批服务", "").split("、") if x.strip()]
        for i, name in enumerate(parts or ["项目用地"], 1):
            rows.append([f"{i}、{name}", "批次用地报批", "以勘测定界为准",
                         "权属与地类核查工作量大", "耕地占补与社保审核要件前置",
                         f"约 {max(int((_dur(ctx) - 30) / max(len(parts), 1)), 10)} 天"])
    return {"caption": "表1-1 各地块报批需求差异化分析表",
            "headers": ["地块名称", "报批类型", "用地规模", "重点难点",
                        "特殊关注事项", "预计耗时"],
            "rows": rows}


