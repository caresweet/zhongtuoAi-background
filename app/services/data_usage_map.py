def usage_of(field: str) -> str:
    """返回该字段「用在哪」的可读描述（用于弹窗提示）。"""
    items = FIELD_USAGE.get(field) or []
    return "、".join(u for u, _ in items) if items else ""


def attach_usage(missing_fields: list) -> list:
    """给缺失字段列表补上 used_in 说明（供前端弹窗显示）。"""
    for f in (missing_fields or []):
        if isinstance(f, dict) and not f.get("used_in"):
            f["used_in"] = usage_of(f.get("key", ""))
    return missing_fields
