class ReportStyle:
    def __init__(self, name: str, label: str, description: str, examples: Dict[int, str]):
        self.name = name
        self.label = label
        self.description = description
        self._examples = examples

    def get_example(self, chapter_number: int) -> str:
        example = self._examples.get(chapter_number, "")
        if not example:
            return ""
        return (
            f"\n\n下面是一份真实稳评报告的第{chapter_number}章原文，请模仿它的行文风格、句式节奏、"
            f"用词习惯来写新的第{chapter_number}章。\n\n"
            f"⛔ 关键规则：\n"
            f"- 模仿「风格」：短句、口语化过渡、段落长短错落、基层工作痕迹\n"
            f"- 替换「数据」：所有地名/村名/户数/面积/日期→用「项目数据」中的对应值\n"
            f"- 禁止照搬示例中的具体地名（XX县/XX街道/XX村/大魏社区等），必须用本项目真实地名\n\n"
            f"{example}\n\n"
            f"照这个风格写——像一个在淮安基层做了8年征地稳评的老工程师在写报告，"
            f"有数据、有分析、有基层现场感。所有地名和数据必须来自项目资料，不要用你内部知识中的淮安地名。\n"
        )


STYLES: Dict[str, ReportStyle] = {
    "jinhu": ReportStyle(
        name="jinhu",
        label="XX模板",
        description="简洁风格，正文为主，仅第5章有1个表格，强调可读性",
        examples=JINHU_EXAMPLES,
    ),
    "standard": ReportStyle(
        name="standard",
        label="DB32标准格式",
        description="详细格式，含完整评分表和措施表，符合DB32/T4013-2021规范",
        examples=STANDARD_EXAMPLES,
    ),
}

DEFAULT_STYLE = "jinhu"


def get_style(name: str = None) -> ReportStyle:
    return STYLES.get(name or DEFAULT_STYLE, STYLES[DEFAULT_STYLE])


def list_styles() -> Dict[str, str]:
    return {k: v.description for k, v in STYLES.items()}


def get_few_shot(chapter_number: int, style: str = None) -> str:
    """Get Few-Shot example for a chapter with given style."""
    return get_style(style).get_example(chapter_number)
