# 匹配行首「（一）xxx」形式的模板小节标题
_SECTION_RE = re.compile(r'^（([一二三四五六七八九十]+)）\s*(.+)$')


def sectionize(template_text: str, chapter_number: int) -> str:
    """把模板里的「（一）小节名」提升为可识别的二级标题 `### （一）小节名`。

    编号**保留模板原样的中文序号**（人工模板《模版（洪泽征地稳评报告）》章内小节
    一律用（一）（二）（三），不用 4.1/4.2），只负责标记层级。
    """
    out = []
    for line in str(template_text or "").splitlines():
        m = _SECTION_RE.match(line.strip())
        if m:
            out.append(f"### （{m.group(1)}）{m.group(2).strip()}")
            continue
        out.append(line)
    return "\n".join(out)


