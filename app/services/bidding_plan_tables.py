def build_table(key: str, ctx: Dict[str, Any]) -> Spec | None:
    fn = PLAN_TABLES.get(key)
    if not fn:
        return None
    try:
        spec = fn(ctx or {})
    except Exception:
        return None
    if not spec.get("headers") or not spec.get("rows"):
        return None
    return spec
