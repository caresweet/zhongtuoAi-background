_PLACEHOLDER_RE = re.compile(r"\{([a-z_][a-z0-9_]*)\}")


def render_template(template: str, values: Optional[Dict[str, Any]] = None) -> str:
    """用事实值渲染模板；未取到值的占位符回退到 MISSING_POLICY 的中性表述。

    Args:
        template: 含 `{key}` 占位符的模板文本。
        values: 事实卡取值（可为 None）。

    Returns:
        渲染后的文本。**保证不残留 `{xxx}` 占位符**。
    """
    vals = {k: v for k, v in (values or {}).items() if v not in (None, "", "【待补充】")}

    def _sub(m: re.Match) -> str:
        key = m.group(1)
        if key in vals:
            return str(vals[key])
        # 日期/周期类占位符给通用表述，其余走中性兜底
        if key.endswith("_date") or key.endswith("_period"):
            return "评估工作期间"
        if key.endswith("_days"):
            return "7"
        if key.endswith("_members") or key == "leader":
            return "稳评工作组相关人员"
        if key == "funding_text":
            return "本决策资金由属地财政统筹，"
        if key == "compensation_doc":
            return "现行征地区片综合地价执行标准文件"
        return MISSING_POLICY.get(key, "本项目相关单位")

    return _PLACEHOLDER_RE.sub(_sub, str(template or ""))


